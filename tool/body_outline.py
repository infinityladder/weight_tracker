"""Regenerates lib/body_outline.dart from the body pictures.

Run from the project root after changing a picture or its rect in
lib/body_map.dart (bodyImageRects):

    python tool/body_outline.py

Needs Pillow and numpy. For each picture it records, every 2 units down the
200 x 440 box, the leftmost and rightmost solid (non-background) point, so the
layout can keep cards off the body.
"""

import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STEP = 2  # box units per row

# Must match bodyImages and bodyImageRects in lib/body_map.dart:
# Figure name -> (picture, (left, top, width, height)).
BODIES = {
    'male': ('images/body_log_male.png', (0, 38.37, 200, 363.27)),
    'female': ('images/body_log_female.png', (0, 29.25, 200, 381.5)),
    'maleDark': ('images/body_log_male_dark_skin.png', (-9.94, 43.22, 213.26, 356.25)),
    'femaleDark': ('images/body_log_female_dark_skin.png', (4.91, 24.51, 198.99, 391.86)),
}


def outline(path, rect):
    left, top, width, height = rect
    alpha = np.asarray(Image.open(os.path.join(ROOT, path)).convert('RGBA'))[:, :, 3] > 128
    ph, pw = alpha.shape
    rows = []
    for i in range(440 // STEP):
        y0, y1 = i * STEP, (i + 1) * STEP
        p0 = int(np.floor((y0 - top) / height * ph))
        p1 = int(np.ceil((y1 - top) / height * ph))
        p0, p1 = max(p0, 0), min(p1, ph)
        cols = np.nonzero(alpha[p0:p1].any(axis=0))[0] if p1 > p0 else []
        if len(cols) == 0:
            rows.append(None)
        else:
            rows.append((round(left + cols[0] / pw * width), round(left + (cols[-1] + 1) / pw * width)))
    return rows


def main():
    out = [
        '// Generated by tool/body_outline.py from the body pictures; do not edit.',
        '',
        "import 'models.dart';",
        '',
        '/// Rows every [outlineStep] units down the 200 x 440 box: the leftmost and',
        '/// rightmost solid point of the body, or null where there is none.',
        f'const outlineStep = {STEP};',
        '',
        'const bodyOutlines = <Figure, List<(int, int)?>>{',
    ]
    for name, (path, rect) in BODIES.items():
        rows = outline(path, rect)
        cells = ', '.join('null' if r is None else f'({r[0]}, {r[1]})' for r in rows)
        out.append(f'  Figure.{name}: [{cells}],')
    out.append('};')
    dest = os.path.join(ROOT, 'lib', 'body_outline.dart')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', dest)


if __name__ == '__main__':
    main()
